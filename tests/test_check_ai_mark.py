# AI-assisted: written with Claude Code (Anthropic) for the NASA Space Apps 2026 entry; reviewed by the team.
"""Tests for scripts/check_ai_mark.py: every code and data file must say that AI helped make it."""
import json
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))
from check_ai_mark import check  # noqa: E402


class CheckAiMarkTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)

    def tearDown(self):
        self._tmp.cleanup()

    def write(self, rel, text):
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return rel

    def test_code_file_with_header_passes(self):
        f = self.write("app/main.py", "# AI-assisted: written with Claude Code\nprint(1)\n")
        self.assertEqual(check(self.root, [f]), [])

    def test_code_file_without_header_fails(self):
        f = self.write("app/main.py", "print(1)\n")
        self.assertEqual(len(check(self.root, [f])), 1)

    def test_header_must_be_near_the_top(self):
        f = self.write("site/app.js", "\n" * 12 + "// AI-assisted\n")
        self.assertEqual(len(check(self.root, [f])), 1)

    def test_html_comment_header_passes(self):
        f = self.write("site/index.html", "<!doctype html>\n<!-- AI-assisted: Claude Code -->\n<html></html>\n")
        self.assertEqual(check(self.root, [f]), [])

    def test_data_json_with_key_passes(self):
        f = self.write("data/cases.json", json.dumps({"_ai_assisted": "generated by data/generate.py", "rows": []}))
        self.assertEqual(check(self.root, [f]), [])

    def test_data_json_without_key_fails(self):
        f = self.write("data/cases.json", json.dumps({"rows": []}))
        self.assertEqual(len(check(self.root, [f])), 1)

    def test_data_json_top_level_list_fails(self):
        f = self.write("data/cases.json", json.dumps([1, 2]))
        self.assertEqual(len(check(self.root, [f])), 1)

    def test_data_json_invalid_fails(self):
        f = self.write("data/cases.json", "{not json")
        self.assertEqual(len(check(self.root, [f])), 1)

    def test_other_data_file_listed_in_data_card_passes(self):
        self.write("DATA_CARD.md", "Files: `data/cases.csv` (synthetic, AI-assisted)\n")
        f = self.write("data/cases.csv", "a,b\n1,2\n")
        self.assertEqual(check(self.root, [f]), [])

    def test_other_data_file_not_in_data_card_fails(self):
        self.write("DATA_CARD.md", "Nothing listed yet\n")
        f = self.write("data/cases.csv", "a,b\n")
        self.assertEqual(len(check(self.root, [f])), 1)

    def test_other_data_file_without_data_card_fails(self):
        f = self.write("data/cases.csv", "a,b\n")
        self.assertEqual(len(check(self.root, [f])), 1)

    def test_docs_and_vendored_files_are_ignored(self):
        files = [
            self.write("README.md", "no header\n"),
            self.write("node_modules/x/index.js", "no header\n"),
            self.write("site/package.json", "{}"),
        ]
        self.assertEqual(check(self.root, files), [])

    def test_empty_repo_passes(self):
        self.assertEqual(check(self.root, []), [])

    # Review round 1 (PR #1): edge cases.
    def test_mark_on_line_ten_passes_and_line_eleven_fails(self):
        ok = self.write("a/ok.py", "\n" * 9 + "# AI-assisted\n")
        late = self.write("a/late.py", "\n" * 10 + "# AI-assisted\n")
        self.assertEqual(check(self.root, [ok, late]), [f"{late}: no 'AI-assisted' header in the first 10 lines"])

    def test_mark_match_ignores_case(self):
        f = self.write("a/main.py", "# ai-Assisted: Claude Code\n")
        self.assertEqual(check(self.root, [f]), [])

    def test_uppercase_suffix_is_still_code(self):
        f = self.write("a/MAIN.PY", "print(1)\n")
        self.assertEqual(len(check(self.root, [f])), 1)

    def test_listed_but_missing_file_is_skipped(self):
        self.assertEqual(check(self.root, ["a/gone.py"]), [])

    def test_directory_entry_is_skipped(self):
        (self.root / "sub").mkdir()
        self.assertEqual(check(self.root, ["sub"]), [])

    def test_nested_data_folder_counts_as_data(self):
        f = self.write("site/data/cases.json", json.dumps({"rows": []}))
        self.assertEqual(len(check(self.root, [f])), 1)

    def test_private_is_skipped_only_at_top_level(self):
        top = self.write("private/notes.py", "no header\n")
        nested = self.write("src/private/a.py", "no header\n")
        self.assertEqual(check(self.root, [top, nested]), [f"{nested}: no 'AI-assisted' header in the first 10 lines"])

    def test_package_json_inside_data_is_checked(self):
        f = self.write("data/package.json", json.dumps({"name": "x"}))
        self.assertEqual(len(check(self.root, [f])), 1)

    def test_data_card_needs_the_exact_backticked_path(self):
        self.write("DATA_CARD.md", "Files: `mydata/a.csv` and `data/a.csv.bak`\n")
        f = self.write("data/a.csv", "a\n")
        self.assertEqual(len(check(self.root, [f])), 1)

    def test_markdown_inside_data_is_documentation(self):
        f = self.write("data/README.md", "How the generator works\n")
        self.assertEqual(check(self.root, [f]), [])

    def test_data_json_with_bom_passes(self):
        f = self.write("data/cases.json", "﻿" + json.dumps({"_ai_assisted": "yes"}))
        self.assertEqual(check(self.root, [f]), [])


if __name__ == "__main__":
    unittest.main()
